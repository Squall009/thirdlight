/** Build one PCM mono 48 kHz 16-bit WAV (44-byte header) for a sine tone. */
function buildWav(freqHz, durationMs, peakAmp = 0.4) {
  const rate = 48000;
  const frames = Math.floor((durationMs / 1000) * rate);
  const dataBytes = new ArrayBuffer(frames * 2);
  const dv = new DataView(dataBytes);
  for (let i = 0; i < frames; i += 1) {
    // A short tone with a linear fade-out envelope (no click).
    const t = i / rate;
    const env = i < frames * 0.7 ? 1 : (frames - i) / (frames * 0.3);
    const sample = Math.sin(2 * Math.PI * freqHz * t) * peakAmp * env;
    dv.setInt16(i * 2, Math.max(-32767, Math.min(32767, Math.round(sample * 32767))), true);
  }
  const dataSize = frames * 2;
  const out = new Uint8Array(44 + dataSize);
  const v = new DataView(out.buffer);
  const writeStr = (off, s) => { for (let i = 0; i < s.length; i += 1) out[off + i] = s.charCodeAt(i); };
  writeStr(0, 'RIFF'); v.setUint32(4, 36 + dataSize, true); writeStr(8, 'WAVE');
  writeStr(12, 'fmt '); v.setUint32(16, 16, true);
  v.setUint16(20, 1, true); // PCM
  v.setUint16(22, 1, true); // mono
  v.setUint32(24, rate, true);
  v.setUint32(28, rate * 2, true); // byteRate
  v.setUint16(32, 2, true); // blockAlign
  v.setUint16(34, 16, true); // bitsPerSample
  writeStr(36, 'data'); v.setUint32(40, dataSize, true);
  out.set(new Uint8Array(dataBytes), 44);
  return out;
}

/* ------------------------------------------------------------------ GLB --- */

class BinWriter {
  constructor() { this.bytes = []; }
  push(data) {
    const offset = Math.ceil(this.bytes.length / 4) * 4;
    while (this.bytes.length < offset) this.bytes.push(0);
    for (const b of data) this.bytes.push(b & 0xff);
    return { offset, length: data.length };
  }
  byteLength() { return this.bytes.length; }
  padded() {
    const out = new Uint8Array(Math.ceil(this.bytes.length / 4) * 4);
    out.set(this.bytes, 0);
    return out;
  }
}

function f32(values) {
  const b = new ArrayBuffer(values.length * 4);
  const v = new DataView(b);
  values.forEach((x, i) => v.setFloat32(i * 4, x, true));
  return [...new Uint8Array(b)];
}
function u16(values) {
  const b = new ArrayBuffer(values.length * 2);
  const v = new DataView(b);
  values.forEach((x, i) => v.setUint16(i * 2, x, true));
  return [...new Uint8Array(b)];
}

/** A unit box (8 vertices, 12 triangles) as POSITION + indices byte arrays. */
function boxBytes(halfX, halfY, halfZ) {
  const x = halfX, y = halfY, z = halfZ;
  const positions = f32([
    -x, -y, -z, x, -y, -z, x, y, -z, -x, y, -z,
    -x, -y, z, x, -y, z, x, y, z, -x, y, z,
  ]);
  const indices = u16([
    0, 1, 2, 0, 2, 3, 4, 6, 5, 4, 7, 6,
    0, 4, 5, 0, 5, 1, 1, 5, 6, 1, 6, 2,
    3, 2, 6, 3, 6, 7, 0, 3, 7, 0, 7, 4,
  ]);
  return { positions, indices };
}

/** Pack a glTF 2.0 GLB (JSON chunk + BIN chunk). */
function packGlb(jsonText, bin) {
  const jsonBytes = new TextEncoder().encode(jsonText);
  const jsonPadded = new Uint8Array(Math.ceil(jsonBytes.length / 4) * 4);
  jsonPadded.set(jsonBytes, 0);
  jsonPadded.fill(0x20, jsonBytes.length);
  const total = 12 + 8 + jsonPadded.length + 8 + bin.length;
  const out = new Uint8Array(total);
  const v = new DataView(out.buffer);
  v.setUint32(0, 0x46546c67, true);
  v.setUint32(4, 2, true);
  v.setUint32(8, total, true);
  v.setUint32(12, jsonPadded.length, true);
  v.setUint32(16, 0x4e4f534a, true);
  out.set(jsonPadded, 20);
  const binHeader = 20 + jsonPadded.length;
  v.setUint32(binHeader, bin.length, true);
  v.setUint32(binHeader + 4, 0x004e4942, true);
  out.set(bin, binHeader + 8);
  return out;
}

/**
 * Build a rigid multi-part model with named rotation/translation clips.
 * `parts`: [{ name, half, translation, clipNode: true|false }] — each part is
 * a box mesh on its own node (rigid internal parts; no skin/bones). `clips`:
 * [{ name, duration, perPart: { [partName]: { rot, trans } } }] — each clip
 * animates a rotation (and optionally translation) channel per part.
 */
function buildRigidModel({ generator, sceneName, parts, clips, colors, rootTranslation }) {
  const bin = new BinWriter();
  const bufferViews = [];
  const accessors = [];
  const meshes = [];
  const nodes = [];
  const animations = [];
  const materials = [];

  // One mesh + material per part (rigid; each part is a node with a mesh).
  parts.forEach((p, i) => {
    const box = boxBytes(p.half[0], p.half[1], p.half[2]);
    const pos = bin.push(box.positions);
    const idx = bin.push(box.indices);
    bufferViews.push({ buffer: 0, byteOffset: pos.offset, byteLength: pos.length, target: 34962 });
    bufferViews.push({ buffer: 0, byteOffset: idx.offset, byteLength: idx.length, target: 34963 });
    const [hx, hy, hz] = p.half;
    accessors.push({
      bufferView: 2 * i, componentType: 5126, count: 8, type: 'VEC3',
      min: [-hx, -hy, -hz], max: [hx, hy, hz],
    });
    accessors.push({ bufferView: 2 * i + 1, componentType: 5123, count: 36, type: 'SCALAR' });
    meshes.push({ name: `${p.name}Mesh`, primitives: [{ attributes: { POSITION: 2 * i }, indices: 2 * i + 1, material: i, mode: 4 }] });
    const c = colors[i] ?? [0.6, 0.6, 0.6, 1];
    materials.push({ name: `${p.name}Mat`, pbrMetallicRoughness: { baseColorFactor: c, metallicFactor: 0.1, roughnessFactor: 0.8 } });
    nodes.push({ name: p.name, mesh: i, translation: p.translation ?? [0, 0, 0] });
  });

  // A root node holding all parts (rigid hierarchy, unit scale, no physics).
  nodes.unshift({ name: 'Root', children: parts.map((_, i) => i + 1), ...(rootTranslation ? { translation: rootTranslation } : {}) });
  // Re-index: parts are now nodes 1..n.

  clips.forEach((clip, ci) => {
    const samplers = [];
    const channels = [];
    Object.entries(clip.perPart).forEach(([partName, spec]) => {
      const partIndex = parts.findIndex((p) => p.name === partName);
      if (partIndex < 0) return;
      const nodeIndex = partIndex + 1; // parts are nodes 1..n
      // A two-frame linear clip (identity -> target) for each present channel.
      // Sampler input/output reference the accessors actually pushed.
      const duration = clip.duration ?? 1;
      const times = bin.push(f32([0, duration]));
      bufferViews.push({ buffer: 0, byteOffset: times.offset, byteLength: times.length });
      const timesAccessor = accessors.length;
      accessors.push({ bufferView: bufferViews.length - 1, componentType: 5126, count: 2, type: 'SCALAR', min: [0], max: [duration] });
      if (spec.rot) {
        const [x, y, z, w] = spec.rot;
        const n = Math.hypot(x, y, z, w);
        const r = bin.push(f32([0, 0, 0, 1, x / n, y / n, z / n, w / n]));
        bufferViews.push({ buffer: 0, byteOffset: r.offset, byteLength: r.length });
        const outAccessor = accessors.length;
        accessors.push({ bufferView: bufferViews.length - 1, componentType: 5126, count: 2, type: 'VEC4' });
        samplers.push({ input: timesAccessor, output: outAccessor, interpolation: 'LINEAR' });
        channels.push({ sampler: samplers.length - 1, target: { node: nodeIndex, path: 'rotation' } });
      }
      if (spec.trans) {
        const tr = bin.push(f32([0, 0, 0, spec.trans[0], spec.trans[1], spec.trans[2]]));
        bufferViews.push({ buffer: 0, byteOffset: tr.offset, byteLength: tr.length });
        const outAccessor = accessors.length;
        accessors.push({ bufferView: bufferViews.length - 1, componentType: 5126, count: 2, type: 'VEC3' });
        samplers.push({ input: timesAccessor, output: outAccessor, interpolation: 'LINEAR' });
        channels.push({ sampler: samplers.length - 1, target: { node: nodeIndex, path: 'translation' } });
      }
    });
    animations.push({ name: clip.name, samplers, channels });
  });

  const json = {
    asset: { version: '2.0', generator },
    scene: 0,
    scenes: [{ name: sceneName, nodes: [0] }],
    nodes,
    meshes,
    materials,
    accessors,
    bufferViews,
    buffers: [{ byteLength: bin.byteLength() }],
    animations,
  };
  return packGlb(JSON.stringify(json), bin.padded());
}

