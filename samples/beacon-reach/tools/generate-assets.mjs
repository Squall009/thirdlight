function main() {
  const audioDir = join(ASSETS, 'audio');
  const modelDir = join(ASSETS, 'model');
  mkdirSync(audioDir, { recursive: true });
  mkdirSync(modelDir, { recursive: true });
  writeFileSync(join(SAMPLE_ROOT, 'LICENSE'), LICENSE_TEXT);

  const provenance = {
    sample: 'beacon-reach',
    generatedBy: 'samples/beacon-reach/tools/generate-assets.mjs',
    license: LICENSE_ID,
    licenseText: join(SAMPLE_ROOT, 'LICENSE'),
    assets: [],
  };

  for (const cue of CUES) {
    const bytes = buildWav(cue.freqHz, cue.durationMs);
    const path = `audio/cue-${cue.name}.wav`;
    writeFileSync(join(ASSETS, path), bytes);
    provenance.assets.push({
      id: `audio-${cue.name}`,
      kind: 'audio',
      path,
      sourceDigest: sha256Hex(bytes),
      sourceByteLength: bytes.byteLength,
      profile: 'pcm-wav',
      recipe: { sampleRate: 48000, channels: 1, bitsPerSample: 16, freqHz: cue.freqHz, durationMs: cue.durationMs },
    });
  }

  for (const [name, bytes] of [['courier', COURIER], ['beacon', BEACON]]) {
    const path = `model/${name}.glb`;
    writeFileSync(join(ASSETS, path), bytes);
    provenance.assets.push({
      id: `model-${name}`,
      kind: 'model',
      path,
      sourceDigest: sha256Hex(bytes),
      sourceByteLength: bytes.byteLength,
      profile: 'glb-gltf2',
      clips: name === 'courier' ? ['Idle', 'Run', 'Airborne'] : [],
    });
  }

  writeFileSync(join(ASSETS, 'provenance.json'), JSON.stringify(provenance, null, 2) + '\n');
  console.log(`generated ${provenance.assets.length} assets under ${ASSETS}`);
  for (const a of provenance.assets) console.log(`  ${a.id}: ${a.path} ${a.sourceByteLength}B ${a.sourceDigest.slice(0, 12)}…`);
}

main();