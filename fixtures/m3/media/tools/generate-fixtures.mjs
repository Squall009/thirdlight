// ---------------------------------------------------------------------------
// binary helpers
// ---------------------------------------------------------------------------
const u16 = (v) => { const b = Buffer.alloc(2); b.writeUInt16LE(v & 0xffff, 0); return b; };
const u32 = (v) => { const b = Buffer.alloc(4); b.writeUInt32LE(v >>> 0, 0); return b; };
const ascii = (s) => Buffer.from(s, 'latin1');
const f32 = (values) => { const b = Buffer.alloc(values.length * 4); values.forEach((v, i) => b.writeFloatLE(v, i * 4)); return b; };
const u16arr = (values) => { const b = Buffer.alloc(values.length * 2); values.forEach((v, i) => b.writeUInt16LE(v, i * 2)); return b; };
const sha256 = (buf) => createHash('sha256').update(buf).digest('hex');

/** commands.md §6.6 rule 2 canonical JSON: sorted keys, no whitespace. */
function canonicalJson(value) {
  if (Array.isArray(value)) return `[${value.map(canonicalJson).join(',')}]`;
  if (value !== null && typeof value === 'object') {
    const keys = Object.keys(value).sort();
    return `{${keys.map((k) => `${JSON.stringify(k)}:${canonicalJson(value[k])}`).join(',')}}`;
  }
  return JSON.stringify(value);
}
const canonicalDigest = (value) => sha256(Buffer.from(canonicalJson(value), 'utf8'));

