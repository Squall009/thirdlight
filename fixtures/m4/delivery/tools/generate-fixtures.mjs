const index = {};
for (const [rel, buf] of [...written.entries()].sort((a, b) => (a[0] < b[0] ? -1 : 1))) {
  index[rel[0] === '/' ? rel : rel.replace(/\\/g, '/')] = { byteLength: buf.length, sha256: sha256(buf) };
}
putJson('index.json', index);

let failed = 0;
for (const [rel, buf] of [...written.entries()].sort((a, b) => (a[0] < b[0] ? -1 : 1))) {
  const abs = join(ROOT, rel);
  if (CHECK) {
    if (!existsSync(abs)) {
      console.error(`MISSING (expected): ${rel}`);
      failed += 1;
    } else {
      const disk = readFileSync(abs);
      if (!disk.equals(buf)) {
        console.error(`DIFFERS (on-disk ≠ generated): ${rel}`);
        failed += 1;
      }
    }
  } else {
    mkdirSync(dirname(abs), { recursive: true });
    writeFileSync(abs, buf);
    console.log(`wrote ${rel} (${buf.length} bytes)`);
  }
}
if (CHECK) {
  if (failed === 0) console.log(`check OK: ${written.size} files byte-identical`);
  else process.exit(1);
} else {
  console.log(`generated ${written.size} files under ${ROOT}`);
}
