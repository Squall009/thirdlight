/** defaults ⊕ explicit over the registry, registry order (delivery §3.1). */
function resolveSettings(explicit) {
  const out = {};
  for (const row of SETTINGS_REGISTRY) {
    const value = Object.prototype.hasOwnProperty.call(explicit, row.key)
      ? explicit[row.key]
      : row.default;
    out[row.key] = value;
  }
  return out;
}

