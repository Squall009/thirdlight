/**
 * @param {object} spec
 *   clipNames: string[]                animation names, in stored order
 *   channelsPerClip: number            rotation channels per clip (node 2)
 *   rootMotion: boolean                add a translation channel on root node 0 (A6)
 *   skin: boolean                      add a `skins` array + node.skin (A2)
 *   generator: string
 */
function buildGlb(spec) {
  const clipNames = spec.clipNames ?? ['Idle', 'Run', 'Airborne'];
  const channelsPerClip = spec.channelsPerClip ?? 1;
  const rootMotion = spec.rootMotion === true;
  const skin = spec.skin === true;
  const generator = spec.generator ?? 'thirdlight-m4-delivery-fixtures';

  const blobs = [];
  let binLength = 0;
  const bufferViews = [];
  const accessors = [];

  const addBlob = (buf, target) => {
    const pad = (4 - (binLength % 4)) % 4;
    if (pad > 0) { blobs.push(Buffer.alloc(pad)); binLength += pad; }
    const byteOffset = binLength;
    blobs.push(buf); binLength += buf.length;
    const bv = { buffer: 0, byteOffset, byteLength: buf.length };
    if (target !== undefined) bv.target = target;
    bufferViews.push(bv);
    return bufferViews.length - 1;
  };
  const addAccessor = (componentType, type, count, bufferView, min, max) => {
    const a = { bufferView, componentType, count, type };
    if (min !== undefined) a.min = min;
    if (max !== undefined) a.max = max;
    accessors.push(a);
    return accessors.length - 1;
  };

  // --- geometry: two triangles sharing one position/index pair ---------------
  const positions = addBlob(f32([0, 0, 0, 1, 0, 0, 0, 1, 0]), 34962);
  const indices = addBlob(u16arr([0, 1, 2]), 34963);
  const posAccessor = addAccessor(5126, 'VEC3', 3, positions, [0, 0, 0], [1, 1, 0]);
  const idxAccessor = addAccessor(5123, 'SCALAR', 3, indices, [0], [2]);

  const meshes = [
    { name: 'BodyMesh', primitives: [{ attributes: { POSITION: posAccessor }, indices: idxAccessor }] },
    { name: 'ArmMesh', primitives: [{ attributes: { POSITION: posAccessor }, indices: idxAccessor }] },
  ];

  const nodes = [
    { name: 'Runner', children: [1, 2] },
    { name: 'Body', mesh: 0, translation: [0, 0, 0] },
    { name: 'Arm', mesh: 1, translation: [0.2, 0.3, 0] },
  ];
  if (skin) nodes[0].skin = 0;

  // Two keyframes per clip; exact committed values (deterministic).
  const quatFor = (count) => {
    if (count === 2) return [0, 0, 0, 1, 0, 0, 0.5, 0.8660254037844386];
    const out = [];
    for (let i = 0; i < count; i += 1) {
      const angle = i * 0.01;
      out.push(0, 0, Math.sin(angle / 2), Math.cos(angle / 2));
    }
    return out;
  };

  const animations = [];
  for (let c = 0; c < clipNames.length; c += 1) {
    const times = [0, 1];
    const timeBlob = addBlob(f32(times));
    const timeAccessor = addAccessor(5126, 'SCALAR', times.length, timeBlob, [times[0]], [times[times.length - 1]]);
    const quatBlob = addBlob(f32(quatFor(times.length)));
    const quatAccessor = addAccessor(5126, 'VEC4', times.length, quatBlob);
    const samplers = [{ input: timeAccessor, output: quatAccessor, interpolation: 'LINEAR' }];
    const channels = [];
    for (let i = 0; i < channelsPerClip; i += 1) {
      channels.push({ sampler: 0, target: { node: 2, path: 'rotation' } });
    }
    if (rootMotion && c === 0) {
      const transBlob = addBlob(f32([0, 0, 0, 0.25, 0, 0]));
      const transAccessor = addAccessor(5126, 'VEC3', 2, transBlob);
      samplers.push({ input: timeAccessor, output: transAccessor, interpolation: 'LINEAR' });
      channels.push({ sampler: 1, target: { node: 0, path: 'translation' } });
    }
    animations.push({ name: clipNames[c], samplers, channels });
  }

  const json = {
    asset: { version: '2.0', generator },
    scene: 0,
    scenes: [{ name: 'RunnerScene', nodes: [0] }],
    nodes,
    meshes,
    accessors,
    bufferViews,
    buffers: [{ byteLength: binLength }],
    animations,
  };
  if (skin) json.skins = [{ joints: [1, 2], skeleton: 0 }];

  const bin = Buffer.concat(blobs);
  let jsonBytes = Buffer.from(JSON.stringify(json), 'utf8');
  while (jsonBytes.length % 4 !== 0) jsonBytes = Buffer.concat([jsonBytes, Buffer.from(' ')]);
  let binBytes = bin;
  while (binBytes.length % 4 !== 0) binBytes = Buffer.concat([binBytes, Buffer.alloc(1)]);

  const total = 12 + 8 + jsonBytes.length + 8 + binBytes.length;
  return Buffer.concat([
    u32(0x46546c67), u32(2), u32(total),
    u32(jsonBytes.length), u32(0x4e4f534a), jsonBytes,
    u32(binBytes.length), u32(0x004e4942), binBytes,
  ]);
}

