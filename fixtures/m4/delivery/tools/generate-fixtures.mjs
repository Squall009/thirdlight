// ---------------------------------------------------------------------------
// binary helpers (same pattern as the M3 media fixtures — self-contained)
// ---------------------------------------------------------------------------
const u16 = (v) => { const b = Buffer.alloc(2); b.writeUInt16LE(v & 0xffff, 0); return b; };
const u32 = (v) => { const b = Buffer.alloc(4); b.writeUInt32LE(v >>> 0, 0); return b; };
const f32 = (values) => { const b = Buffer.alloc(values.length * 4); values.forEach((v, i) => b.writeFloatLE(v, i * 4)); return b; };
const u16arr = (values) => { const b = Buffer.alloc(values.length * 2); values.forEach((v, i) => b.writeUInt16LE(v, i * 2)); return b; };
const sha256 = (buf) => createHash('sha256').update(buf).digest('hex');

/**
 * Accepted block-digest rule (sessions.md §17.1.1 / M3 delivery §2.4):
 * `sha256(JSON.stringify(value, null, 2) + "\n")` UTF-8 over the declared
 * canonical key order (the object is constructed in canonical order);
 * `null` hashes the four bytes `null` (no newline — the accepted special
 * case).
 */
const blockDigest = (value) => {
  if (value === null) return sha256(Buffer.from('null', 'utf8'));
  return sha256(Buffer.from(`${JSON.stringify(value, null, 2)}\n`, 'utf8'));
};

