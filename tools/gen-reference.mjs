#!/usr/bin/env node
/**
 * Generate the engine reference (`docs/manual/reference/`).
 *
 * Everything in it comes from the code, so it cannot drift from the build:
 *
 * - objects, components and content documents: project-model's descriptor
 *   registry (type, unit, range, default, tooltip, Scene handle);
 * - command ops: the validator's op list (`MUTATION_OPS`) and its per-op
 *   argument union, with the declarations the shapes name;
 * - the script API: the runtime's `BehaviorContext` and what it reaches
 *   (the model tools/gen-behavior-api.mjs builds the editor's typings from);
 * - node graphs: every registered graph kind's catalogue (`GRAPH_KINDS`);
 * - limits and defaults: the constants the packages export, each under the
 *   file that defines it.
 *
 * Output is plain markdown, one area per page (split when a page grows past
 * `PAGE_BYTES_MAX`), every section with a stable anchor, plus `index.md` and
 * `index.json` (topic → page and section) for the documentation lookup.
 * It is deterministic: stable order, no dates, no machine paths.
 *
 * `node tools/gen-reference.mjs` rewrites the directory; `--check` exits 1
 * naming the stale pages. tools/gen-reference.test.mjs runs the same check in
 * the unit suite.
 */
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import process from 'node:process';
import { fileURLToPath } from 'node:url';

import { behaviorApiModel } from './gen-behavior-api.mjs';
import { GENERATED_NOTE, code, pageText, table } from './reference/markdown.mjs';
import { descriptorPages } from './reference/pages-descriptors.mjs';
import { graphPages } from './reference/pages-graphs.mjs';
import { limitPages } from './reference/pages-limits.mjs';
import { descriptorShapeNames } from './reference/fields.mjs';
import { opPages, typePages } from './reference/pages-ops.mjs';
import { scriptPages } from './reference/pages-script.mjs';
import { constantOwners, createModelProgram, declarationsNamed, opShapes, typeCollector } from './reference/ts-model.mjs';
import { VALUE_PACKAGES, loadValues } from './reference/values.mjs';

const ROOT = resolve(fileURLToPath(import.meta.url), '..', '..');
export const OUTPUT_DIR = join(ROOT, 'docs', 'manual', 'reference');
export const REGENERATE = 'node tools/gen-reference.mjs';

/** Replace every `@@anchor@@` link target with its page (and fail on an unknown anchor). */
function resolveLinks(pages) {
  const where = new Map();
  for (const p of pages) {
    for (const s of p.sections) {
      if (where.has(s.id)) throw new Error(`gen-reference: section id "${s.id}" is used twice (${where.get(s.id)} and ${p.file})`);
      where.set(s.id, p.file);
    }
  }
  for (const p of pages) {
    for (const s of p.sections) {
      s.text = s.text.replace(/@@([^@]+)@@/g, (_, id) => {
        const file = where.get(id);
        if (file === undefined) throw new Error(`gen-reference: ${p.file} links to an unknown section "${id}"`);
        return file === p.file ? `#${id}` : `${file}#${id}`;
      });
    }
  }
}

function indexFiles(pages) {
  const topics = {};
  const add = (topic, at) => {
    if (topic in topics) throw new Error(`gen-reference: topic "${topic}" is defined twice`);
    topics[topic] = at;
  };
  for (const p of pages) {
    for (const t of p.topics) add(t, { page: p.file });
    for (const s of p.sections) for (const t of s.topics) add(t, { page: p.file, section: s.id });
  }
  const sortedTopics = Object.fromEntries(Object.keys(topics).sort().map((k) => [k, topics[k]]));
  // One entry per line: small, and a change shows as a one-line diff.
  const pageLines = pages.map((p) => JSON.stringify({ page: p.file, title: p.title, sections: p.sections.filter((s) => s.level <= 2).map((s) => ({ id: s.id, title: s.title })) }));
  const topicLines = Object.entries(sortedTopics).map(([k, v]) => `${JSON.stringify(k)}: ${JSON.stringify(v)}`);
  const json = `{\n"format": 1,\n"note": ${JSON.stringify(`Generated by ${REGENERATE}. topics: lookup key -> page and section anchor.`)},\n"pages": [\n${pageLines.join(',\n')}\n],\n"topics": {\n${topicLines.join(',\n')}\n}\n}\n`;
  const contents = (p) => {
    const top = p.sections.filter((s) => s.level === 2);
    return top.length === 0 || top.length > 12 ? `${p.sections.length} sections` : top.map((s) => s.title).join(', ');
  };
  const rows = pages.map((p) => [`[${p.title}](${p.file})`, contents(p)]);
  const md =
    `# Engine reference\n\n${GENERATED_NOTE}\n\n` +
    'What the engine offers, generated from its source: the objects, components and content documents a project holds, the command ops that edit them, the script API, the node graph catalogues and the limits. ' +
    `For a lookup by topic (\`component.light\`, \`op.editBlocks\`, \`ctx.grid\`, \`node.material.pbr\`, \`limit.MAX_TAGS\`), \`index.json\` maps each topic to its page and section.\n\n` +
    table(['Page', 'Sections'], rows) +
    `\nThe topic kinds: ${[...new Set(Object.keys(sortedTopics).map((t) => t.split('.')[0]))].map(code).join(', ')}.\n`;
  return { md, json };
}

/** file name → text of every reference file. */
export async function generateReference() {
  const values = await loadValues(ROOT);
  const pm = values['project-model'];
  const commands = values['commands'];
  const program = createModelProgram(ROOT, VALUE_PACKAGES);
  const collector = typeCollector(program, ROOT);
  const shapes = opShapes(program, ROOT, commands.MUTATION_OPS, collector);
  collector.addExported('project-model', descriptorShapeNames(pm.DESCRIPTORS), 'a descriptor shape');
  const types = collector.done();
  const [request, success, failure] = declarationsNamed(program, ROOT, 'packages/commands/src/types.ts', ['MutationRequest', 'MutationSuccess', 'MutationFailure']);
  const owners = constantOwners(program, ROOT, VALUE_PACKAGES);
  const pages = [
    ...descriptorPages(pm.DESCRIPTORS),
    ...opPages(shapes, types, commands.MUTATION_OPS, pm.DESCRIPTORS, { request, results: `${success}\n\n${failure}` }),
    ...typePages(types),
    ...scriptPages(behaviorApiModel()),
    ...graphPages(pm.GRAPH_KINDS),
    ...limitPages(values, owners),
  ];
  const files = new Set();
  for (const p of pages) {
    if (files.has(p.file) || p.file === 'index.md') throw new Error(`gen-reference: two pages are named ${p.file}`);
    files.add(p.file);
  }
  resolveLinks(pages);
  const out = new Map(pages.map((p) => [p.file, pageText(p)]));
  const index = indexFiles(pages);
  out.set('index.md', index.md);
  out.set('index.json', index.json);
  for (const [file, text] of out) {
    if (text.includes(ROOT) || /\/home\/|\/tmp\//.test(text)) throw new Error(`gen-reference: ${file} names a machine path`);
  }
  return new Map([...out.entries()].sort((a, b) => a[0].localeCompare(b[0])));
}

/** The pages that differ from the checked-in directory: changed, missing and extra files. */
export function staleFiles(generated, dir = OUTPUT_DIR) {
  const present = existsSync(dir) ? readdirSync(dir).filter((f) => /\.(md|json)$/.test(f)) : [];
  const stale = [];
  for (const [file, text] of generated) {
    const path = join(dir, file);
    if (!existsSync(path)) stale.push(`${file} (missing)`);
    else if (readFileSync(path, 'utf8') !== text) stale.push(`${file} (out of date)`);
  }
  for (const f of present) if (!generated.has(f)) stale.push(`${f} (no longer generated)`);
  return stale.sort();
}

if (process.argv[1] !== undefined && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const generated = await generateReference();
  if (process.argv.includes('--check')) {
    const stale = staleFiles(generated);
    if (stale.length > 0) {
      console.error(`gen-reference: FAIL — stale reference pages: ${stale.join(', ')}; run ${REGENERATE}`);
      process.exit(1);
    }
    console.log('gen-reference: up to date');
  } else {
    mkdirSync(OUTPUT_DIR, { recursive: true });
    for (const f of readdirSync(OUTPUT_DIR)) if (/\.(md|json)$/.test(f) && !generated.has(f)) rmSync(join(OUTPUT_DIR, f));
    for (const [file, text] of generated) writeFileSync(join(OUTPUT_DIR, file), text);
    console.log(`gen-reference: wrote ${generated.size} files to docs/manual/reference`);
  }
}
